type TranslationKey = keyof typeof dictionary.ar;

type LocaleContextValue = {
  language: Language;
  direction: "rtl" | "ltr";
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey) => string;
};

const LocaleContext = createContext<LocaleContextValue | undefined>(undefined);

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const requested = new URLSearchParams(window.location.search).get("lang");
      if (requested === "ar" || requested === "en") return requested;
      const saved = localStorage.getItem("lqta.language");
      return saved === "en" ? "en" : "ar";
    } catch {
      return "ar";
    }
  });
  const manualLanguageChoice = useRef(false);
  const preferredLanguageUserId = useRef<string | null>(null);
  const direction = language === "ar" ? "rtl" : "ltr";
  useEffect(() => {
    const requested = new URLSearchParams(window.location.search).get("lang");
    if (requested === "ar" || requested === "en") return;
    const applySavedAccountLanguage = (event?: Event) => {
      const detail = (
        event as
          | CustomEvent<Language | { language: Language; userId: string }>
          | undefined
      )?.detail;
      const languageFromEvent =
        typeof detail === "string" ? detail : detail?.language;
      if (detail && typeof detail === "object" && detail.userId) {
        if (
          preferredLanguageUserId.current &&
          preferredLanguageUserId.current !== detail.userId
        ) {
          manualLanguageChoice.current = false;
        }
        preferredLanguageUserId.current = detail.userId;
      }
      if (languageFromEvent === "ar" || languageFromEvent === "en") {
        if (!manualLanguageChoice.current) setLanguageState(languageFromEvent);
        return;
      }
      try {
        const account = JSON.parse(
          localStorage.getItem("lqta.session-user-info") ?? "null"
        ) as { preferredLanguage?: unknown } | null;
        if (
          !manualLanguageChoice.current &&
          (account?.preferredLanguage === "ar" ||
            account?.preferredLanguage === "en")
        )
          setLanguageState(account.preferredLanguage);
      } catch {
        /* an anonymous or malformed cache must not block the locale */
      }
    };
    applySavedAccountLanguage();
    window.addEventListener(
      "lqta:preferred-language",
      applySavedAccountLanguage
    );
    return () =>
      window.removeEventListener(
        "lqta:preferred-language",
        applySavedAccountLanguage
      );
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    document.body.dataset.language = language;
    try {
      localStorage.setItem("lqta.language", language);
    } catch {
      /* local storage unavailable */
    }
  }, [direction, language]);

  const setLanguage = useCallback((nextLanguage: Language) => {
    manualLanguageChoice.current = true;
    setLanguageState(nextLanguage);
  }, []);
  const value = useMemo<LocaleContextValue>(
    () => ({
      language,
      direction,
      setLanguage,
      toggleLanguage: () => setLanguage(language === "ar" ? "en" : "ar"),
      t: key => dictionary[language][key],
    }),
    [direction, language, setLanguage]
  );

  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useLocale() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLocale must be used within LocaleProvider");
  return context;
}
